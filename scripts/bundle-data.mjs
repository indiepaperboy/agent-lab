import { readdir, readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const files = {};
for (const name of (await readdir(new URL('data/', root))).sort()) {
  files[name] = await readFile(new URL(`data/${name}`, root), 'utf8');
}
await writeFile(new URL('src/data.js', root), `// Generated by scripts/bundle-data.mjs from data/.\nglobalThis.AgentData = Object.freeze(${JSON.stringify(files, null, 2)});\n`);
